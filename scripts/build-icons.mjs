const css = fs.readFileSync(remixCss, 'utf8')
const codepoints = {}
for (const [name, remixName] of Object.entries(icons)) {
  const match = css.match(
    new RegExp(
      `\\.ri-${remixName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}:before\\s*\\{\\s*content:\\s*"\\\\([0-9a-f]+)"`,
    ),
  )
  if (!match) throw new Error(`Missing Remix icon: ${remixName}`)
  codepoints[name] = Number.parseInt(match[1], 16)
}

function findSvg(name) {
  const dirs = fs.readdirSync(path.join(root, 'node_modules/remixicon/icons'))
  for (const dir of dirs) {
    const candidate = path.join(
      root,
      'node_modules/remixicon/icons',
      dir,
      `${name}.svg`,
    )
    if (fs.existsSync(candidate)) return candidate
  }
  throw new Error(`Missing Remix SVG: ${name}`)
}

const sources = {}
for (const [name, remixName] of Object.entries(icons)) {
  const svg = fs.readFileSync(findSvg(remixName))
  const png = await sharp(svg, { density: 384 })
    .resize(48, 48, {
      fit: 'contain',
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .png({ compressionLevel: 9, palette: true })
    .toBuffer()
  sources[name] = `data:image/png;base64,${png.toString('base64')}`
}

const iconTs = `// Generated by scripts/build-icons.mjs from Remix Icon 4.9.1. Do not edit by hand.
export const ICON_SOURCES = ${JSON.stringify(sources, null, 2)} as const

export type IconName = keyof typeof ICON_SOURCES
`
fs.writeFileSync(path.join(outDir, 'icons.ts'), iconTs)
if (fs.existsSync(path.join(outDir, 'iconfont.css'))) {
  fs.rmSync(path.join(outDir, 'iconfont.css'))
}
