export function translate(
  locale: Locale,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  const dict = dictionaries[locale] ?? en
  let value = dict[key] ?? en[key] ?? key
  if (params) {
    for (const [name, replacement] of Object.entries(params)) {
      value = value.split(`{${name}}`).join(String(replacement))
    }
  }
  return value
}

export function createTranslator(localeInput?: string) {
  const locale = normalizeLocale(localeInput)
  return {
    locale,
    t: (key: MessageKey, params?: Record<string, string | number>) =>
      translate(locale, key, params),
  }
}

export type Translator = ReturnType<typeof createTranslator>

export function formatDateTime(timestamp: number, locale: Locale): string {
  try {
    return new Intl.DateTimeFormat(locale, {
      month: 'short',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    }).format(new Date(timestamp))
  } catch {
    return new Date(timestamp).toLocaleString()
  }
}

export function formatRelativeTime(timestamp: number, locale: Locale): string {
  const diff = Date.now() - timestamp
  const minute = 60_000
  const hour = 60 * minute
  const day = 24 * hour
  if (diff < minute) return locale === 'zh-Hans' ? '刚刚' : 'just now'
  if (diff < hour)
    return locale === 'zh-Hans'
      ? `${Math.floor(diff / minute)} 分钟前`
      : `${Math.floor(diff / minute)}m ago`
  if (diff < day)
    return locale === 'zh-Hans'
      ? `${Math.floor(diff / hour)} 小时前`
      : `${Math.floor(diff / hour)}h ago`
  return formatDateTime(timestamp, locale)
}
